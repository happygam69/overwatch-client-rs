"""Build dev/INDEX.md from the tool headers.

    python make_index.py            # write dev/INDEX.md
    python make_index.py --check    # fail if the file is stale

Every tracked script carries a one-line docstring saying what question it
answers. This turns those lines into the index, so the tool list cannot drift
from the tools. Run it after adding, renaming or re-scoping a script.
"""

from __future__ import annotations

import ast
import pathlib
import subprocess
import sys

DEV = pathlib.Path(__file__).resolve().parent
INDEX = DEV / "INDEX.md"

# Scripts that are not tools of their own, or that have no header.
SKIP = {"make_index.py"}


def summary(path: pathlib.Path) -> str:
    """The first meaningful line of the module docstring."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return "(no parseable header)"
    doc = ast.get_docstring(tree) or ""
    for line in doc.splitlines():
        line = line.strip()
        if line:
            return line
    return "(no header)"


def tool_paths() -> list[pathlib.Path]:
    """Every `.py` under `dev/` that git would ship.

    Ignored files are excluded on purpose. `dev/data/`, `dev/decompiles/` and
    the rest are untracked analysis output, so indexing them made the committed
    INDEX.md unreproducible: it carried rows a clean checkout does not have, and
    `--check` failed there (the first CI run proved it). `--others
    --exclude-standard` still picks up a new tool that has not been `git add`ed.
    """
    try:
        out = subprocess.run(
            [
                "git",
                "-C",
                str(DEV.parent),
                "ls-files",
                "-z",
                "--cached",
                "--others",
                "--exclude-standard",
                "--",
                "dev",
            ],
            check=True,
            capture_output=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        # No git (an unpacked tree): nothing in it is ignored anyway.
        return sorted(DEV.rglob("*.py"))
    found = {DEV.parent / p for p in out.decode("utf-8", "replace").split("\0") if p}
    return sorted(p for p in found if p.suffix == ".py" and p.is_file())


def rows() -> list[tuple[str, str, int]]:
    out = []
    for path in tool_paths():
        if path.name in SKIP:
            continue
        rel = path.relative_to(DEV).as_posix()
        lines = path.read_text(encoding="utf-8", errors="replace").count("\n") + 1
        out.append((rel, summary(path), lines))
    return out


def render(table: list[tuple[str, str, int]]) -> str:
    head = [
        "# dev/ - the analysis tools",
        "",
        "Generated by `python make_index.py`; run `--check` to see if it is stale.",
        "Every tool is read-only against the install and the Ghidra project.",
        "The current workflow uses the tools named in `docs/tools.md`.",
        "",
        "Only files git ships are listed: untracked analysis output under",
        "`dev/data/` (decompiles, extracted fixtures, one-off probes) is ignored by",
        "the whitelist `.gitignore` and deliberately absent, so this file stays",
        "reproducible on a clean checkout.",
        "",
        "| tool | what it answers | lines |",
        "|---|---|---|",
    ]
    body = [f"| `{name}` | {text} | {n} |" for name, text, n in table]
    return "\n".join(head + body) + "\n"


def main() -> int:
    table = rows()
    text = render(table)
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != text:
            print("dev/INDEX.md is stale; run: python make_index.py")
            return 1
        print(f"dev/INDEX.md is up to date ({len(table)} tools)")
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote {INDEX} ({len(table)} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
