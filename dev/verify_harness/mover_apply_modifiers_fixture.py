def build_body(case, i: int) -> bytes:
    recs, index, start, d8, flags, feature, gate654, *rest = case
    scan = rest[0] if rest else None
    rng = random.Random(0x4D4F_4453 ^ i)
    body = bytearray(rng.getrandbits(8) for _ in range(BODY_LEN))
    body[0:8] = (ARENA_BASE + VTABLE_OFF).to_bytes(8, "little")
    body[8:16] = BODY_SERVICE.to_bytes(8, "little")
    body[0xE4:0xE8] = index.to_bytes(4, "little")
    body[0x10E4:0x10E8] = (start & 0xFFFFFFFF).to_bytes(4, "little")
    body[0x10D8:0x10DC] = (d8 & 0xFFFFFFFF).to_bytes(4, "little")
    body[0x10D0:0x10D4] = (flags & 0xFFFFFFFF).to_bytes(4, "little")
    if scan is None:
        body[0xA78:0xA7C] = (0).to_bytes(4, "little")
    else:
        count, lo, hi, flag1 = scan
        body[0xA78:0xA7C] = count.to_bytes(4, "little")
        body[0xA70:0xA78] = (ARENA_BASE + 0x1000).to_bytes(8, "little")
        entry = 0x1000
        body[entry + 0x1C:entry + 0x20] = lo.to_bytes(4, "little")
        body[entry + 0x20:entry + 0x24] = hi.to_bytes(4, "little")
        body[0x1A81] = flag1
    body[0x1A81] = 0
    body[0x1AD8:0x1AE0] = (0).to_bytes(8, "little")
    body[0x654] = gate654
    body[0x878:0x87C] = len(recs).to_bytes(4, "little")
    body[0x870:0x878] = (ARENA_BASE + 0x880).to_bytes(8, "little")
    service = SERVICE_OFF
    body[service + 0x28:service + 0x30] = DECODE_DESC.to_bytes(8, "little")
    if feature:
        body[service + 0x118:service + 0x120] = (1 << 29).to_bytes(8, "little")
    else:
        body[service + 0x118:service + 0x120] = (0).to_bytes(8, "little")
    for k, rec in enumerate(recs):
        lo, hi, kind, op, value, bound = rec
        base = 0x880 + k * 0x38
        struct.pack_into("<i", body, base + 0x1C, lo)
        struct.pack_into("<i", body, base + 0x20, hi)
        struct.pack_into("<i", body, base + 0x28, kind)
        struct.pack_into("<i", body, base + 0x2C, op)
        struct.pack_into("<I", body, base + 0x30, value)
        struct.pack_into("<I", body, base + 0x34, bound)
    return bytes(body)


def make_args(i: int) -> List[ArgSpec]:
    case = CASES[i % len(CASES)]
    recs = case[0]
    feature = case[5]
    blob = bytearray(len(recs) * 0x38)
    for k, rec in enumerate(recs):
        lo, hi, kind, op, value, bound = rec
        base = k * 0x38
        struct.pack_into("<i", blob, base + 0x1C, lo)
        struct.pack_into("<i", blob, base + 0x20, hi)
        struct.pack_into("<i", blob, base + 0x28, kind)
        struct.pack_into("<i", blob, base + 0x2C, op)
        struct.pack_into("<I", blob, base + 0x30, value)
        struct.pack_into("<I", blob, base + 0x34, bound)
    records = bytes(blob)
    vtable = bytearray(0x80)
    vtable[0x68:0x70] = NOP68.to_bytes(8, "little")
    vtable[0x70:0x78] = GATE70.to_bytes(8, "little")
    return [
        ArgSpec(kind="ptr", mem=build_body(case, i), arena_offset=0),
        ArgSpec(kind="u64", bits=ARENA_BASE),
        ArgSpec(kind="ptr", mem=records, arena_offset=0x6900),
        ArgSpec(kind="u64", bits=1),
        ArgSpec(kind="u64", bits=1 if feature else 0),
        ArgSpec(kind="f64", value=G1),
        ArgSpec(kind="f64", value=G2),
        ArgSpec(kind="ptr", mem=bytes(vtable), arena_offset=VTABLE_OFF),
    ]
